/**
 * Regenerates artifacts/api-server/src/lib/bootstrapStatements.ts from the
 * Drizzle schema, so a fresh database can be created at boot.
 *
 *   pnpm --filter @workspace/db exec drizzle-kit generate \
 *     --schema=./src/schema/index.ts --out=./drizzle
 *   node scripts/generate-schema-bootstrap.mjs
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const dir = "lib/db/drizzle";
const file = readdirSync(dir).filter((name) => name.endsWith(".sql")).sort().pop();
if (!file) throw new Error("No generated SQL found. Run drizzle-kit generate first.");

const sql = readFileSync(join(dir, file), "utf8");
const statements = sql
  .split("--> statement-breakpoint")
  .map((part) => part.trim())
  .filter(Boolean)
  .map((statement) => {
    // drizzle-kit terminates every statement with ";", which would become an
    // empty statement (and a syntax error) once wrapped in a DO block.
    const body = statement.replace(/;+\s*$/, "");
    let next = body.startsWith('CREATE TABLE "')
      ? body.replace('CREATE TABLE "', 'CREATE TABLE IF NOT EXISTS "')
      : body;
    if (next.toUpperCase().startsWith("ALTER TABLE")) {
      next = `DO $$ BEGIN\n${next};\nEXCEPTION WHEN duplicate_object THEN NULL; WHEN invalid_table_definition THEN NULL; END $$`;
    }
    return next;
  });

const header = `/**
 * Generated by scripts/generate-schema-bootstrap.mjs from ${file}.
 * DO NOT EDIT BY HAND.
 */
export const BOOTSTRAP_STATEMENTS: string[] = [
`;
writeFileSync(
  "artifacts/api-server/src/lib/bootstrapStatements.ts",
  header + statements.map((statement) => `  ${JSON.stringify(statement)}`).join(",\n") + ",\n];\n",
);
console.log(`Wrote ${statements.length} bootstrap statements from ${file}`);
